#!/usr/bin/env python3
"""Check new and worsened CCN-15 functions in project source."""
import argparse
from collections import defaultdict
import os
from pathlib import Path, PurePosixPath
import subprocess
import sys

import lizard

THRESHOLD = 15
SOURCE_SUFFIXES = {".go", ".js", ".jsx", ".py", ".ts", ".tsx"}
DEPENDENCY_DIRS = {"node_modules", "vendor"}
GENERATED_SUFFIXES = ("_generated.go", ".gen.go", ".generated.go")
GENERATED_PATHS = {"web/app.js"}


def is_source_path(filename):
    path = PurePosixPath(filename)
    return (
        path.suffix in SOURCE_SUFFIXES
        and filename not in GENERATED_PATHS
        and not DEPENDENCY_DIRS.intersection(path.parts)
        and not path.name.endswith(GENERATED_SUFFIXES)
    )


def is_generated(source):
    markers = ("// Code generated", "# Code generated", "/* Code generated")
    return any(
        line.lstrip().startswith(markers) and "DO NOT EDIT." in line
        for line in source.splitlines()[:5]
    )


def function_groups(filename, source):
    info = lizard.analyze_file.analyze_source_code(filename, source)
    groups = defaultdict(list)
    for function in info.function_list:
        receiver = function.long_name.partition(")")[0] + ")" if function.long_name.startswith("(") else ""
        signature = (receiver, function.name, tuple(function.full_parameters))
        groups[signature].append(function)
    for functions in groups.values():
        # ponytail: Lizard omits dynamic-language class scope; AST names if duplicate methods move.
        functions.sort(key=lambda function: function.start_line)
    return groups


def violations(before, after):
    found = []
    function_count = 0
    for filename in sorted(set(before) | set(after)):
        old = function_groups(filename, before.get(filename, ""))
        new = function_groups(filename, after.get(filename, ""))
        function_count += sum(len(functions) for functions in new.values())
        for signature, functions in new.items():
            previous = old.get(signature, [])
            for index, function in enumerate(functions):
                current_ccn = function.cyclomatic_complexity
                if current_ccn <= THRESHOLD:
                    continue
                old_function = previous[index] if index < len(previous) else None
                if old_function is None:
                    found.append((filename, function.name, None, current_ccn))
                elif current_ccn > old_function.cyclomatic_complexity:
                    found.append(
                        (filename, function.name, old_function.cyclomatic_complexity, current_ccn)
                    )
    return found, function_count


def synthetic_source(branches):
    lines = ["def sample(value):"]
    for index in range(branches):
        lines.extend((f"    if value == {index}:", "        value += 1"))
    lines.append("    return value")
    return "\n".join(lines) + "\n"


def synthetic_go_source(branches, receiver=None):
    signature = "func sample(value int) int {"
    if receiver:
        signature = f"func (r *{receiver}) sample(value int) int {{"
    lines = ["package main", signature]
    for index in range(branches):
        lines.extend((f"if value == {index} {{", "value++", "}"))
    lines.extend(("return value", "}"))
    return "\n".join(lines) + "\n"


def synthetic_web_source(branches, class_name=None):
    if class_name:
        lines = [f"class {class_name} {{", "sample(value: number): number {"]
    else:
        lines = ["function sample(value: number): number {"]
    for index in range(branches):
        lines.extend((f"if (value === {index}) {{", "value++;", "}"))
    lines.extend(("return value;", "}"))
    if class_name:
        lines.append("}")
    return "\n".join(lines) + "\n"

def self_test():
    assert is_source_path("homes.go")
    assert is_source_path("answers.go")
    assert is_source_path("station.go")
    assert is_source_path("scripts/quality.py")
    assert not is_source_path("vendor/example.go")
    assert not is_source_path("web/node_modules/example.js")
    assert not is_source_path("web/app.js")
    assert is_generated("// Code generated by tool; DO NOT EDIT.\n")
    assert len(violations({}, {"homes.go": synthetic_go_source(15)})[0]) == 1
    assert len(violations({}, {"answers.tsx": synthetic_web_source(15)})[0]) == 1
    home_16 = synthetic_go_source(15, "Home").partition("\n")[2]
    station_17 = synthetic_go_source(16, "Station").partition("\n")[2]
    home_17 = synthetic_go_source(16, "Home").partition("\n")[2]
    station_16 = synthetic_go_source(15, "Station").partition("\n")[2]
    go_before = {"homes.go": "package main\n" + home_16 + station_17}
    go_reordered = {"homes.go": "package main\n" + station_17 + home_16}
    go_worsened = {"homes.go": "package main\n" + home_17 + station_16}
    assert not violations(go_before, go_reordered)[0]
    assert len(violations(go_before, go_worsened)[0]) == 1
    web_before = {"app.tsx": synthetic_web_source(15, "Alpha") + synthetic_web_source(16, "Beta")}
    web_worsened = {"app.tsx": synthetic_web_source(16, "Alpha") + synthetic_web_source(15, "Beta")}
    assert len(violations(web_before, web_worsened)[0]) == 1
    high = {"sample.py": synthetic_source(15)}
    higher = {"sample.py": synthetic_source(16)}
    lower = {"sample.py": synthetic_source(14)}
    assert not violations(high, high)[0]
    assert len(violations({}, high)[0]) == 1
    assert len(violations(lower, high)[0]) == 1
    assert not violations(higher, high)[0]


def git_output(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True).stdout


def source_paths(output):
    paths = {os.fsdecode(path) for path in output.split(b"\0") if path}
    return {filename for filename in paths if is_source_path(filename)}


def load_sources(base):
    before = {}
    base_paths = source_paths(git_output("ls-tree", "-r", "-z", "--name-only", base))
    for filename in sorted(base_paths):
        source = git_output("show", f"{base}:{filename}").decode()
        if not is_generated(source):
            before[filename] = source
    after = {}
    current_paths = git_output("ls-files", "--cached", "--others", "--exclude-standard", "-z")
    for filename in sorted(source_paths(current_paths)):
        path = Path(filename)
        if not path.is_file():
            continue
        source = path.read_text(encoding="utf-8")
        if not is_generated(source):
            after[filename] = source
    return before, after


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", help="base commit to compare")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return 0
    if not args.base:
        parser.error("--base is required unless --self-test is used")
    try:
        base = git_output("rev-parse", "--verify", f"{args.base}^{{commit}}").decode().strip()
        before, after = load_sources(base)
    except (OSError, subprocess.CalledProcessError, UnicodeDecodeError):
        print("complexity check could not load its baseline or source files", file=sys.stderr)
        return 2
    failures, function_count = violations(before, after)
    if not function_count:
        print("complexity check parsed no source functions", file=sys.stderr)
        return 2
    for filename, name, old_ccn, current_ccn in failures:
        change = "new" if old_ccn is None else f"worsened from {old_ccn}"
        print(f"{filename}:{name}: {change} to CCN {current_ccn} (limit {THRESHOLD})", file=sys.stderr)
    if failures:
        return 1
    print(
        f"No new or worsened functions exceed CCN {THRESHOLD} "
        f"({function_count} functions checked across {len(after)} files)."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
